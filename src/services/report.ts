// Shareable report export: turn an entity record into a self-contained
// Markdown document that keeps every provenance pointer — so where it is
// pasted, the reader can verify each claim at its source.

import type { EntityData } from '@/types/entityTypes';

/** Compact relative time for "checked 3 minutes ago" style stamps. */
export const timeAgo = (iso?: string): string => {
  if (!iso) return '';
  const then = new Date(iso).getTime();
  if (Number.isNaN(then)) return '';
  const secs = Math.max(0, Math.round((Date.now() - then) / 1000));
  if (secs < 60) return 'just now';
  const mins = Math.round(secs / 60);
  if (mins < 60) return `${mins} min ago`;
  const hours = Math.round(mins / 60);
  if (hours < 24) return `${hours} h ago`;
  return new Date(iso).toLocaleDateString();
};

const PROVIDER_LABEL: Record<string, string> = {
  wikidata: 'Wikidata',
  wikipedia: 'Wikipedia',
  website: 'Official site',
  platform: 'Platform profile',
};

/** Compose the full Markdown report for one entity record. */
export const buildReportMarkdown = (entity: EntityData): string => {
  const lines: string[] = [];

  lines.push(`# ${entity.name} — public evidence record`);
  lines.push('');
  lines.push(
    `Generated by Ethical Checker on ${new Date().toLocaleString()}. ` +
    'The score is evidence coverage — how much first-party transparency material was ' +
    'found in public sources — not a verdict on whether the entity is ethical.',
  );
  lines.push('');

  lines.push('## Score');
  lines.push(`**${entity.ethicalScore}/100** evidence coverage${entity.website ? ` · ${entity.website}` : ''}`);
  lines.push('');

  lines.push('## Sources');
  if (entity.sources?.length) {
    for (const source of entity.sources) {
      const checked = source.fetchedAt ? ` (checked ${timeAgo(source.fetchedAt)})` : '';
      lines.push(`- **${PROVIDER_LABEL[source.provider] ?? source.provider}** — ${source.title}${checked}`);
      lines.push(`  ${source.url}`);
      if (source.excerpt) {
        lines.push(`  > ${source.excerpt.replace(/\s+/g, ' ')}`);
      }
    }
  } else {
    lines.push('_No public sources recorded for this entry (sample catalog record)._');
  }
  lines.push('');

  if (entity.disclosures?.length) {
    lines.push('## Disclosures found');
    for (const d of entity.disclosures) {
      lines.push(`- **${d.title}** — ${d.description}${d.link ? `\n  ${d.link}` : ''}`);
    }
    lines.push('');
  }

  if (entity.controversies?.length) {
    lines.push('## Controversies and issues');
    for (const c of entity.controversies) {
      lines.push(`- **${c.title}**${c.date ? ` (${c.date})` : ''}`);
      lines.push(`  ${c.description}`);
      if (c.source_url) lines.push(`  Source: ${c.source_url}`);
    }
    lines.push('');
  }

  if (entity.certifications?.length) {
    lines.push('## Certifications (claimed)');
    lines.push(entity.certifications.map((c) => `- ${c}`).join('\n'));
    lines.push('');
  }

  if (entity.categories?.length) {
    lines.push(`_Categories: ${entity.categories.join(', ')}_`);
  }

  return lines.join('\n');
};

/** Copy the report to the clipboard; returns false on failure so the UI can
 *  tell the user instead of pretending it worked. */
export const copyReport = async (entity: EntityData): Promise<boolean> => {
  try {
    await navigator.clipboard.writeText(buildReportMarkdown(entity));
    return true;
  } catch {
    return false;
  }
};
